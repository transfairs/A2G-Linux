"""a2managerbuild.py on a ManagerCode.cs in A2G-Patch's form: no checkout of A2G-Patch needed."""

import base64
import json
import runpy
import sys

import pytest

import a2managerbuild as m


def b64(data, split=4):
    """Convert.FromBase64String as make_manager.py writes it, the string in pieces joined with +."""
    text = base64.b64encode(data).decode()
    pieces = [text[i : i + split] for i in range(0, len(text), split)]
    return 'Convert.FromBase64String("' + '" +\n                "'.join(pieces) + '")'


def build_cs(switch):
    return f"""            new ManagerBuild
            {{
                Switch = 0x{switch:X}, Table = 0x55D5D4, Questions = 0x6BD610, KeyState = 0x6775A8,
                Cases = new uint[] {{ 0x55D5C4, 0x55CFB4 }},
                Regions = new uint[] {{ 0x56E820, 0x603CD0 }},
                Originals = new[]
                {{
                    {b64(b"orig-one")},
                    {b64(b"two")},
                }},
                Symbols = new uint[] {{ 0x55AA10, 0x7836E8 }},
            }},
"""


def manager_cs(builds=3):
    return (
        """// Generated by tools/make_manager.py from tools/manager_events.asm and tools/manager_builds.py. Do not edit.
using System;

namespace A2GPatch
{
    internal static class ManagerCode
    {
        internal static readonly byte[][] Blocks =
        {
            """
        + b64(b"\xb8\x01\x00\x00\x00main")
        + """,
            """
        + b64(b"asks")
        + """,
        };

        internal static readonly int[][] Fields =
        {
            new[] { 0x31, 0x1, 0x1C, 0x0, 0x4C, 0x0, 0x2, -0x14 },
            new[] {  },
        };

        internal static readonly string[] Symbols = { "ShowText", "Texts", "Q13" };

        internal static readonly int[] Cases = { 13, 25 };
        internal static readonly int[][] Entries = { new[] { 0, 0x349 }, new[] { 1, 0x0 } };

        internal static readonly ManagerBuild[] Builds =
        {
"""
        + "".join(build_cs(0x55C90D + i) for i in range(builds))
        + """        };
    }

    internal sealed class ManagerBuild
    {
        public uint Switch, Table, Questions;
        public uint[] Cases;
    }
}
"""
    )


def test_parse():
    data = m.parse(manager_cs())
    assert data["blocks"] == [b"\xb8\x01\x00\x00\x00main".hex(), b"asks".hex()]
    assert data["fields"] == [[[0x31, 1, 0x1C, 0], [0x4C, 0, 2, -0x14]], []]
    assert data["symbols"] == ["ShowText", "Texts", "Q13"]
    assert data["cases"] == [13, 25]
    assert data["entries"] == [[0, 0x349], [1, 0]]
    assert list(data["builds"]) == ["1999", "gog", "2007"]
    assert data["builds"]["gog"] == {
        "switch": 0x55C90E,
        "table": 0x55D5D4,
        "questions": 0x6BD610,
        "keystate": 0x6775A8,
        "cases": [0x55D5C4, 0x55CFB4],
        "regions": [0x56E820, 0x603CD0],
        "originals": [b"orig-one".hex(), b"two".hex()],
        "symbols": [0x55AA10, 0x7836E8],
    }


def test_parse_needs_three_builds():
    with pytest.raises(SystemExit, match="2 builds, expected 3"):
        m.parse(manager_cs(builds=2))


def test_dump_reads_back():
    data = m.parse(manager_cs())
    text = m.dump(data)
    assert json.loads(text) == data
    # braces, a line per key and build, "builds" opened and closed
    assert text.count("\n") == 2 + len(data) - 1 + len(data["builds"]) + 2


def test_the_stored_code_has_its_own_form():
    with open(m.OUTPUT) as f:
        text = f.read()
    assert m.dump(json.loads(text)) == text


def run(monkeypatch, *args):
    monkeypatch.setattr(sys, "argv", ["a2managerbuild.py", *map(str, args)])
    m.main()


def test_main_writes_and_checks(tmp_path, monkeypatch, capsys):
    source = tmp_path / "ManagerCode.cs"
    source.write_text(manager_cs(), encoding="utf-8")
    monkeypatch.setattr(m, "OUTPUT", str(tmp_path / "a2manager.json"))
    run(monkeypatch, source)
    assert json.loads((tmp_path / "a2manager.json").read_text()) == m.parse(manager_cs())
    run(monkeypatch, "--check", source)
    assert "up to date" in capsys.readouterr().out
    source.write_text(manager_cs().replace("0x349", "0x34A"), encoding="utf-8")
    with pytest.raises(SystemExit, match="differs"):
        run(monkeypatch, "--check", source)


def test_main_needs_one_path(monkeypatch):
    with pytest.raises(SystemExit, match=r"a2managerbuild.py \[--check\]"):
        run(monkeypatch, "--check")


def test_runs_as_a_script(tmp_path, monkeypatch):
    source = tmp_path / "ManagerCode.cs"
    source.write_text(manager_cs(), encoding="utf-8")
    monkeypatch.setattr(sys, "argv", ["a2managerbuild.py", "--check", str(source)])
    with pytest.raises(SystemExit, match="differs"):  # the stored file holds A2G-Patch's real code
        runpy.run_path(m.__file__, run_name="__main__")
